/*Bitwise Operations 5*/
#include <stdio.h>
int main ()
{
    int a,b,c;
    a=8;
    b=12;
    c=4;
    printf("%d",a<<a);
    printf("\n%d",a<<b);
    printf("\n%d",a<<c);
    printf("\n%d",b<<a);
    printf("\n%d",b<<b);
    printf("\n%d",b<<c);
    printf("\n%d",c<<a);
    printf("\n%d",c<<b);
    printf("\n%d",c<<c);
    return 0;
}
