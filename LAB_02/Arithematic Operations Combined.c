/*Arithematic Operations Combined 1*/
#include <stdio.h>
int main ()
{
    int a,b,result;
    a=20;
    b=10;
    result = a+b;
    printf("%d",result);
    result = a-b;
    printf("\n%d",result);
    result = a*b;
    printf("\n%d",result);
    result = a/b;
    printf("\n%d",result);
    result = a % b;
    printf("\n%d",result);
    return 0;
}
